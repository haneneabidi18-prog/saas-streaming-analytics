    if st.button("📄 Export Executive Report"):
        pdf_file = generate_pdf(total_views, total_watch_time, total_revenue, insights)

        with open(pdf_file, "rb") as file:
            st.download_button(
                label="Download PDF",
                data=file,
                file_name="streaming_report.pdf",
                mime="application/pdf"
            )
