import streamlit as st

if "authentication_status" not in st.session_state or not st.session_state["authentication_status"]:
    st.warning("Please login from the home page.")
    st.stop()

import pandas as pd
import plotly.express as px
import os
import json
from datetime import datetime

from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet


st.set_page_config(page_title="Dashboard", layout="wide")


def generate_pdf(total_views, total_watch_time, total_revenue, insights):
    file_path = "streaming_report.pdf"

    doc = SimpleDocTemplate(file_path, pagesize=letter)
    styles = getSampleStyleSheet()
    elements = []

    elements.append(Paragraph("Streaming Analytics Executive Report", styles["Title"]))
    elements.append(Spacer(1, 20))

    elements.append(Paragraph("Key Performance Indicators", styles["Heading2"]))
    elements.append(Spacer(1, 10))
    elements.append(Paragraph(f"Total Views: {total_views:,}", styles["Normal"]))
    elements.append(Paragraph(f"Watch Time Minutes: {total_watch_time:,}", styles["Normal"]))
    elements.append(Paragraph(f"Revenue: €{total_revenue:,.2f}", styles["Normal"]))

    elements.append(Spacer(1, 20))
    elements.append(Paragraph("Executive Insights", styles["Heading2"]))
    elements.append(Spacer(1, 10))

    for insight in insights:
        elements.append(Paragraph(f"- {insight}", styles["Normal"]))

    elements.append(Spacer(1, 20))
    elements.append(Paragraph("Generated by Streaming Analytics SaaS", styles["Italic"]))

    doc.build(elements)
    return file_path


def generate_insights(filtered_df, total_views, total_revenue):
    insights = []

    if filtered_df.empty:
        return ["No data available for the selected filters."]

    if "country" in filtered_df.columns and total_revenue > 0:
        country_revenue = filtered_df.groupby("country")["revenue"].sum()
        top_country = country_revenue.idxmax()
        revenue_share = (country_revenue.max() / total_revenue) * 100
        insights.append(f"{top_country} generates {revenue_share:.1f}% of total revenue.")

    if "platform" in filtered_df.columns and total_views > 0:
        platform_views = filtered_df.groupby("platform")["views"].sum()
        top_platform = platform_views.idxmax()
        platform_share = (platform_views.max() / total_views) * 100
        insights.append(f"{top_platform} is the leading device/platform with {platform_share:.1f}% of total views.")

    if "content_title" in filtered_df.columns and total_views > 0:
        content_views = filtered_df.groupby("content_title")["views"].sum()
        top_content = content_views.idxmax()
        content_share = (content_views.max() / total_views) * 100
        insights.append(f"{top_content} is the top-performing content with {content_share:.1f}% of total views.")

    if total_views > 0:
        revenue_per_view = total_revenue / total_views
        insights.append(f"Average revenue per view is €{revenue_per_view:.2f}.")

    return insights


